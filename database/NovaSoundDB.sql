CREATE DATABASE NovaSoundDB;

USE NovaSoundDB;

CREATE TABLE turnos(
	ID_TURNO VARCHAR(10) PRIMARY KEY NOT NULL,
	NOMBRE VARCHAR(30) NOT NULL,
	AREA VARCHAR(30) NOT NULL
);

CREATE TABLE lineas(
	ID_LINEA VARCHAR(10) PRIMARY KEY NOT NULL,
	NOMBRE VARCHAR(30) NOT NULL,
	AREA VARCHAR(30) NOT NULL,
	ID_turno VARCHAR(10) NOT NULL,

	CONSTRAINT fk_idTurno FOREIGN KEY (ID_turno) REFERENCES turnos(ID_TURNO)	
);

CREATE TABLE roles(
	ID_ROL VARCHAR(10) PRIMARY KEY NOT NULL,
	NOMBRE VARCHAR(30) NOT NULL
);


CREATE TABLE usuarios (
	ID_USUARIO VARCHAR(30) PRIMARY KEY NOT NULL,
	NOMBRE VARCHAR(80) NOT NULL,
	APELLIDOS VARCHAR(80) NOT NULL,
	AREA VARCHAR(30) NOT NULL,
	ID_linea VARCHAR(10) NOT NULL,
	ID_turno VARCHAR(10) NOT NULL,
	ID_rol VARCHAR(10) NOT NULL,
	FECHA_INGRESO DATE NOT NULL,

	CONSTRAINT fk_idLinea FOREIGN KEY (ID_linea) REFERENCES lineas(ID_LINEA),
	CONSTRAINT fk_idTurno FOREIGN KEY (ID_turno) REFERENCES turnos(ID_TURNO),
	CONSTRAINT fk_idRol FOREIGN KEY (ID_rol) REFERENCES roles(ID_ROL) 
);

CREATE TABLE clientes (
    ID_CLIENTE INT PRIMARY KEY NOT NULL AUTO_INCREMENT,
    NOMBRE VARCHAR(80) NOT NULL,
    DIRECCION VARCHAR(255) NOT NULL,
    TELEFONO VARCHAR(30),
    CORREO VARCHAR(100)
);

CREATE TABLE productos(
	ID_PRODUCTO VARCHAR(20) PRIMARY KEY NOT NULL,
	NOMBRE VARCHAR(100) NOT NULL,
	DESCRIPCION VARCHAR(255) NOT NULL,
	PRECIO DOUBLE NOT NULL
);

CREATE TABLE ordenes_produccion (
	ID_ORDEN VARCHAR(30) PRIMARY KEY NOT NULL,
	ID_producto VARCHAR(20) NOT NULL,
	ID_cliente INT NOT NULL,
	ID_linea VARCHAR(10) NOT NULL,
	ID_turno VARCHAR(10) NOT NULL,
	CANTIDAD_PRODUCIDA INT NOT NULL,
	COLOR VARCHAR(30) NOT NULL,
	FECHA_INICIO DATETIME NOT NULL,
	FECHA_COMPROMISO DATETIME NOT NULL,
	FECHA_FIN DATETIME,
	ESTATUS VARCHAR(30) NOT NULL,
	TIPO_EMPAQUE VARCHAR(30) NOT NULL,

	CONSTRAINT fk_idProducto FOREIGN KEY (ID_producto) REFERENCES productos(ID_PRODUCTO),
	CONSTRAINT fk_idCliente FOREIGN KEY (ID_cliente) REFERENCES clientes(ID_CLIENTE),
	CONSTRAINT fk_idLinea FOREIGN KEY (ID_linea) REFERENCES lineas(ID_LINEA),
	CONSTRAINT fk_idTurno FOREIGN KEY (ID_turno) REFERENCES turnos(ID_TURNO)	
);

CREATE TABLE incidencias(
	ID_INCIDENCIA INT PRIMARY KEY NOT NULL,
	ID_orden VARCHAR(30) NOT NULL,
	ID_usuario VARCHAR(30) NOT NULL,
	ID_producto VARCHAR(20) NOT NULL,
	FECHA DATETIME NOT NULL,
	DESCRIPCION VARCHAR(255) NOT NULL,

	CONSTRAINT fk_idOrden FOREIGN KEY (ID_orden) REFERENCES ordenes_produccion(ID_ORDEN),
	CONSTRAINT fk_idUsuario FOREIGN KEY (ID_usuario) REFERENCES usuarios(ID_USUARIO),
	CONSTRAINT fk_idProducto FOREIGN KEY (ID_producto) REFERENCES productos(ID_PRODUCTO)
);

CREATE TABLE pruebas_funcionales(
	ID_PRUEBA INT PRIMARY KEY NOT NULL,
	ID_orden VARCHAR(30) NOT NULL,
	ID_producto VARCHAR(20) NOT NULL,
	ESTATUS_PRUEBA VARCHAR(30) NOT NULL,
	OBSERVACIONES VARCHAR(255),       
	ID_usuario VARCHAR(30) NOT NULL,
	FECHA DATETIME NOT NULL,

	CONSTRAINT fk_idOrden FOREIGN KEY (ID_orden) REFERENCES ordenes_produccion(ID_ORDEN),
	CONSTRAINT fk_idProducto FOREIGN KEY (ID_producto) REFERENCES productos(ID_PRODUCTO),
	CONSTRAINT fk_idUsuario FOREIGN KEY (ID_usuario) REFERENCES usuarios(ID_USUARIO)
);

CREATE TABLE cajas(
    ID_CAJA VARCHAR(30) PRIMARY KEY NOT NULL,
	ID_orden VARCHAR(30) NOT NULL,
	ID_producto VARCHAR(20) NOT NULL,
	CANTIDAD_UNIDADES INT NOT NULL,
	FECHA_CREACION DATETIME NOT NULL,
	FECHA_CIERRE DATETIME,
	TIPO_EMPAQUE VARCHAR(30) NOT NULL,
	ESTATUS VARCHAR(30) NOT NULL,

	CONSTRAINT fk_idOrden FOREIGN KEY (ID_orden) REFERENCES ordenes_produccion(ID_ORDEN),
	CONSTRAINT fk_idProducto FOREIGN KEY (ID_producto) REFERENCES productos(ID_PRODUCTO)
);

CREATE TABLE unidades (
    NUMERO_SERIE VARCHAR(50) PRIMARY KEY NOT NULL,
	ETIQUETA VARCHAR(30) NOT NULL,
    ID_orden VARCHAR(30) NOT NULL,
    ID_producto VARCHAR(20) NOT NULL,
    COLOR VARCHAR(30) NOT NULL,
    ESTATUS_PRODUCCION VARCHAR(30) NOT NULL, 
    ESTATUS_CALIDAD VARCHAR(30) NOT NULL,    
    ID_caja VARCHAR(30) NULL,                
    
    CONSTRAINT fk_idOrden FOREIGN KEY (ID_orden) REFERENCES ordenes_produccion(ID_ORDEN),
    CONSTRAINT fk_idProducto FOREIGN KEY (ID_producto) REFERENCES productos(ID_PRODUCTO),
    CONSTRAINT fk_idCaja FOREIGN KEY (ID_caja) REFERENCES cajas(ID_CAJA)
);

CREATE TABLE inspeccion (
    ID_inspeccion INT PRIMARY KEY NOT NULL,
    NUMERO_SERIE VARCHAR(50) NOT NULL,
	ID_usuario VARCHAR(30) NOT NULL,
	ID_orden VARCHAR(30) NOT NULL,
	FECHA DATETIME NOT NULL,
	ESTATUS_PRUEBAS VARCHAR(30) NOT NULL,
	ESTATUS_APARIENCIA VARCHAR(30) NOT NULL,
	ESTATUS_ETIQUETA VARCHAR(30) NOT NULL,
	ESTATUS_ACCESORIOS VARCHAR(30) NOT NULL,
    ESTATUS_FINAL VARCHAR(30) NOT NULL,
    
    CONSTRAINT fk_unidadSerie FOREIGN KEY (NUMERO_SERIE) REFERENCES unidades(NUMERO_SERIE),
	CONSTRAINT fk_idUsuario FOREIGN KEY (ID_usuario) REFERENCES usuarios(ID_USUARIO),
	CONSTRAINT fk_idOrden FOREIGN KEY (ID_orden) REFERENCES ordenes_produccion(ID_ORDEN)
);

CREATE TABLE embarques(
	ID_EMBARQUE INT PRIMARY KEY NOT NULL,
	ID_caja VARCHAR(30) NOT NULL,
	FECHA_EMBARQUE DATETIME NOT NULL,
	DESTINO VARCHAR(100) NOT NULL,
	ESTATUS VARCHAR(30) NOT NULL,

	CONSTRAINT fk_idCaja FOREIGN KEY (ID_caja) REFERENCES cajas(ID_CAJA)

);

CREATE TABLE solicitudes_cambios (
    ID_SOLICITUD INT PRIMARY KEY NOT NULL AUTO_INCREMENT,
    OBJETO VARCHAR(50) NOT NULL,
    ID_usuario VARCHAR(30) NOT NULL,
    FECHA_SOLICITUD DATETIME NOT NULL,
    MOTIVO VARCHAR(255) NOT NULL,
    ESTATUS VARCHAR(30) NOT NULL,
    
    CONSTRAINT fk_idUsuario FOREIGN KEY (ID_usuario) REFERENCES usuarios(ID_USUARIO)
);